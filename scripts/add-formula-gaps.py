def main():
    with open(DATA_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Count new formulas
    new_formula_count = 0
    for part in NEW_PARTS:
        for chapter in part['chapters']:
            new_formula_count += len(chapter.get('formulas', []))

    # Append new parts
    data['parts'].extend(NEW_PARTS)

    # Re-build all_formulas index
    new_all_formulas = []
    for part in data['parts']:
        for chapter in part.get('chapters', []):
            for formula in chapter.get('formulas', []):
                # Add part + chapter references
                formula['part'] = part['title']
                formula['chapter'] = chapter['title']
                formula['chapter_number'] = chapter.get('number')
                new_all_formulas.append(formula)
    data['all_formulas'] = new_all_formulas

    # Update meta
    old_total = data['meta']['total_formulas']
    data['meta']['total_formulas'] = len(new_all_formulas)
    data['meta']['total_parts'] = len(data['parts'])
    data['meta']['total_chapters'] = sum(len(p.get('chapters', [])) for p in data['parts'])

    # Update categories
    cats = {}
    for f in new_all_formulas:
        cat = f['part']
        cats[cat] = cats.get(cat, 0) + 1
    data['meta']['categories'] = cats

    # Write
    with open(DATA_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Added {new_formula_count} new formulas across {len(NEW_PARTS)} new parts")
    print(f"Total formulas: {old_total} → {data['meta']['total_formulas']}")
    print(f"Total parts: {data['meta']['total_parts']}")
    print(f"Total chapters: {data['meta']['total_chapters']}")
    print("\nNew categories:")
    for part in NEW_PARTS:
        n = sum(len(c.get('formulas', [])) for c in part['chapters'])
        print(f"  {n:3d}  {part['title']} (Part {part['roman']})")


if __name__ == '__main__':
    main()
